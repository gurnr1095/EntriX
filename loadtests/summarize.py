"""Build LOADTEST.md from the files in loadtests/results/ (nothing is typed in by hand).

    python -m loadtests.summarize

Numbers come from Locust's CSV output, the environment from environment.json, the invariant
result from invariants.txt. Commentary I wrote after reading the numbers lives in
loadtests/observations.md and is included verbatim.
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "loadtests" / "results"
OUTPUT = ROOT / "LOADTEST.md"
RUNS = [("cache-off", "Caching off"), ("cache-on", "Caching on")]
DETAIL = "GET /events/{id}"


def load_stats(label: str) -> dict[str, dict[str, str]]:
    with open(RESULTS / f"{label}_stats.csv", encoding="utf-8", newline="") as f:
        return {row["Name"]: row for row in csv.DictReader(f)}


def num(row: dict[str, str], key: str) -> float:
    return float(row[key])


def ms(value: float) -> str:
    return f"{value:,.0f}"


def hot_category(invariants: str) -> dict[str, int]:
    """Parse the busiest category out of the invariant report."""
    for line in invariants.splitlines():
        if line.startswith("hot_categories:"):
            name, capacity, count, confirmed_rows, waitlisted_rows = json.loads(
                line.split(": ", 1)[1]
            )[0]
            return {
                "capacity": int(capacity),
                "confirmed_count": int(count),
                "confirmed": int(confirmed_rows),
                "waitlisted": int(waitlisted_rows),
            }
    raise SystemExit("hot_categories line missing from the invariant report")


def factor(before: float, after: float) -> str:
    return f"{before / after:.1f}x lower" if after < before else f"{after / before:.1f}x higher"


def table(stats: dict[str, dict[str, str]]) -> list[str]:
    lines = [
        "| Endpoint | Requests | Failures | Req/s | p50 (ms) | p95 (ms) | p99 (ms) | Max (ms) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    names = [n for n in stats if n != "Aggregated"] + ["Aggregated"]
    for name in names:
        r = stats[name]
        lines.append(
            f"| {name} | {int(num(r, 'Request Count')):,} | {int(num(r, 'Failure Count')):,} "
            f"| {num(r, 'Requests/s'):.1f} | {ms(num(r, '50%'))} | {ms(num(r, '95%'))} "
            f"| {ms(num(r, '99%'))} | {ms(num(r, 'Max Response Time'))} |"
        )
    return lines


def main() -> None:
    data = {}
    for label, _ in RUNS:
        data[label] = {
            "stats": load_stats(label),
            "env": json.loads((RESULTS / f"{label}_environment.json").read_text(encoding="utf-8")),
            "invariants": (RESULTS / f"{label}_invariants.txt").read_text(encoding="utf-8").strip(),
        }

    machine = data["cache-off"]["env"]["machine"]
    load = data["cache-off"]["env"]["load"]
    out: list[str] = [
        "# Load test results",
        "",
        "Generated by `loadtests/summarize.py` from the raw files in `loadtests/results/`. "
        "Every number below comes from those files; none was typed in. "
        "Re-run with `python -m loadtests.run_loadtest` (see the README).",
        "",
        "## Environment",
        "",
        f"- Machine: {machine.get('cpu', 'unknown CPU')}, {machine.get('logical_cpus')} logical CPUs, "
        f"{machine.get('ram_gb')} GB RAM, {machine.get('os')}",
        f"- Docker: {machine.get('docker_version')} (Docker Desktop VM: {machine.get('docker_cpus')} CPUs, "
        f"{machine.get('docker_memory_gb')} GB)",
        f"- Python {machine.get('python')}, Locust {machine.get('locust')}",
        "- Everything ran on this one machine: PostgreSQL 16, Redis 7, MailHog, the API, the "
        "outbox worker **and the load generator itself**, all competing for the same CPUs.",
        f"- API: {data['cache-off']['env']['api_config']['WEB_CONCURRENCY']} uvicorn worker, "
        f"database pool {data['cache-off']['env']['api_config']['DB_POOL_SIZE']} + "
        f"{data['cache-off']['env']['api_config']['DB_MAX_OVERFLOW']} overflow, `AUTH_MODE=dev`.",
        "- The per-IP rate limit was raised to 1,000,000/min for these runs, because all virtual "
        "users share this machine's address. The limiter is covered by `tests/test_rate_limit.py`, "
        "not by this test. The per-user limit (10/min) stayed on.",
        "",
        "## Scenario",
        "",
        f"- Ramp from 0 to {load['peak_users']} virtual users over {load['ramp_seconds']} s, then hold, "
        f"for {load['run_seconds']} s in total. Statistics include the ramp.",
        f"- User mix {load['browse_to_launch_user_ratio']}: **Browse** users call `GET /events` "
        "(30%) and `GET /events/{id}` (70%); **Launch** users each register a brand-new person "
        "(unique email, fresh `Idempotency-Key`) for the same hot category (capacity 500, waitlist on), "
        "so once it fills the rest are waitlisted under the category lock.",
        "- Each virtual user waits 0.5 to 1.5 s between requests.",
        "",
    ]

    for label, title in RUNS:
        stats = data[label]["stats"]
        agg = stats["Aggregated"]
        total = num(agg, "Request Count")
        launch = num(stats["POST /categories/{id}/registrations"], "Request Count")
        out += [
            f"## {title}",
            "",
            *table(stats),
            "",
            f"Registration share of all requests: {launch / total:.1%} "
            f"(browse {1 - launch / total:.1%}).",
            "",
        ]

    off, on = data["cache-off"]["stats"], data["cache-on"]["stats"]
    out += [
        "## Caching on vs off",
        "",
        "| Metric | Caching off | Caching on |",
        "|---|---:|---:|",
    ]
    for name in (DETAIL, "GET /events", "POST /categories/{id}/registrations", "Aggregated"):
        for key, label in (("50%", "p50"), ("95%", "p95"), ("99%", "p99")):
            out.append(
                f"| {name} {label} (ms) | {ms(num(off[name], key))} | {ms(num(on[name], key))} |"
            )
    reg = "POST /categories/{id}/registrations"
    out += [
        f"| Aggregated req/s | {num(off['Aggregated'], 'Requests/s'):.1f} "
        f"| {num(on['Aggregated'], 'Requests/s'):.1f} |",
        "",
        "Percentiles are Locust's own, which are approximate (response times are bucketed).",
        "",
        "Computed from the two tables above:",
        "",
        f"- `{DETAIL}` p50 {ms(num(off[DETAIL], '50%'))} ms to {ms(num(on[DETAIL], '50%'))} ms "
        f"({factor(num(off[DETAIL], '50%'), num(on[DETAIL], '50%'))}), p95 "
        f"{ms(num(off[DETAIL], '95%'))} ms to {ms(num(on[DETAIL], '95%'))} ms "
        f"({factor(num(off[DETAIL], '95%'), num(on[DETAIL], '95%'))}), p99 "
        f"{ms(num(off[DETAIL], '99%'))} ms to {ms(num(on[DETAIL], '99%'))} ms.",
        f"- Registration p50 {ms(num(off[reg], '50%'))} ms to {ms(num(on[reg], '50%'))} ms, "
        f"p95 {ms(num(off[reg], '95%'))} ms to {ms(num(on[reg], '95%'))} ms. Registrations never "
        "read the cache, so any change here is an indirect effect (see Observations).",
        f"- Total throughput {num(off['Aggregated'], 'Requests/s'):.1f} req/s to "
        f"{num(on['Aggregated'], 'Requests/s'):.1f} req/s. Virtual users wait for each response "
        "before sending the next request, so slower responses also mean fewer requests offered.",
        "",
        "## Registrations: what Locust counted vs what the database holds",
        "",
        "| Run | Registrations Locust saw succeed | Rows in the hot category | Confirmed | Waitlisted "
        "| Capacity | Seat counter |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for label, title in RUNS:
        hot = hot_category(data[label]["invariants"])
        seen = int(num(data[label]["stats"][reg], "Request Count")) - int(
            num(data[label]["stats"][reg], "Failure Count")
        )
        out.append(
            f"| {title} | {seen:,} | {hot['confirmed'] + hot['waitlisted']:,} | {hot['confirmed']:,} "
            f"| {hot['waitlisted']:,} | {hot['capacity']:,} | {hot['confirmed_count']:,} |"
        )
    out += [
        "",
        "Confirmed registrations equal the capacity and the seat counter in both runs: "
        "no overbooking. The database can hold slightly more rows than Locust counted; see "
        "Observations.",
        "",
        "## Invariant check after each run",
        "",
    ]
    for label, title in RUNS:
        out += [f"**{title}**", "", "```", data[label]["invariants"], "```", ""]

    observations = ROOT / "loadtests" / "observations.md"
    if observations.exists():
        out += [observations.read_text(encoding="utf-8").strip(), ""]

    out += [
        "## What these numbers are not",
        "",
        "- Not a production benchmark: one laptop running the app, the database and the load "
        "generator together, under Docker Desktop's virtual machine.",
        "- Dev authentication, not Clerk: no JWT verification cost is included.",
        "- One run per configuration, so there is no variance estimate; treat small differences "
        "between the two runs as noise.",
        "- The outbox worker ran during the test, so emails were being sent (to MailHog) while "
        "load was applied.",
        "",
    ]
    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
